/// Defines the font families used in the application.
///
/// Locale mapping (see [AppTypography.fontFamilyByLanguage]):
/// - English (`en`) → [inter]
/// - Persian (`fa`) → [yekanBakh]
/// - Pashto (`ps`) → [vazirmatn]
abstract final class AppFontFamily {
  static const String inter = 'Inter';
  static const String yekanBakh = 'YekanBakh';
  static const String vazirmatn = 'Vazirmatn';
}
